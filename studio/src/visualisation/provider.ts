/**
 * Visualisation providers.
 *
 * The app ships with a LOCAL provider that renders the concept with Three.js in
 * the browser. That is a real-time 3D render, not an AI-generated photograph,
 * and the UI labels it as such.
 *
 * A REMOTE provider can be enabled for photorealistic image generation. No key
 * is ever read in the browser: the app calls an endpoint you host, and that
 * endpoint holds the credentials. Configure with:
 *
 *   VITE_VIZ_PROVIDER=remote
 *   VITE_VIZ_ENDPOINT=https://your-service.example.com/render
 *
 * See README.md for the request and response contract.
 */
import type { Concept, Project } from '@/domain/types';

export type ProviderId = 'local' | 'remote';

export interface RenderRequest {
  project: Project;
  concept: Concept;
  /** Viewpoint hint for the renderer. */
  view: 'aerial' | 'street' | 'garden';
  signal?: AbortSignal;
}

export interface RenderResult {
  /** Image the UI can display, or null when the provider draws directly to a canvas. */
  imageUrl: string | null;
  /** Shown beneath the image so the user knows what they are looking at. */
  caption: string;
  providerId: ProviderId;
}

export interface VisualisationProvider {
  id: ProviderId;
  label: string;
  /** True when the provider can actually run in this environment. */
  available: boolean;
  /** Why it is unavailable, for the UI. */
  unavailableReason?: string;
  render(req: RenderRequest): Promise<RenderResult>;
}

/** The built-in renderer. The heavy lifting happens in ui/viewer. */
export const localProvider: VisualisationProvider = {
  id: 'local',
  label: 'Local 3D render',
  available: true,
  async render(): Promise<RenderResult> {
    // The canvas viewer paints itself; nothing to fetch.
    return {
      imageUrl: null,
      caption: 'Real-time 3D massing render produced in your browser. Not a photograph.',
      providerId: 'local',
    };
  },
};

const endpoint = import.meta.env.VITE_VIZ_ENDPOINT ?? '';
const configured = (import.meta.env.VITE_VIZ_PROVIDER ?? 'local').toLowerCase();

export const remoteProvider: VisualisationProvider = {
  id: 'remote',
  label: 'Photorealistic render service',
  available: configured === 'remote' && endpoint.length > 0,
  unavailableReason:
    'Set VITE_VIZ_PROVIDER=remote and VITE_VIZ_ENDPOINT to your own rendering endpoint. See README.md.',
  async render(req: RenderRequest): Promise<RenderResult> {
    if (!endpoint) throw new Error('No rendering endpoint is configured.');
    const res = await fetch(endpoint, {
      method: 'POST',
      headers: { 'content-type': 'application/json' },
      body: JSON.stringify({
        view: req.view,
        concept: req.concept,
        site: req.project.site,
        brief: req.project.brief,
      }),
      ...(req.signal ? { signal: req.signal } : {}),
    });
    if (!res.ok) {
      throw new Error(`The rendering service replied ${res.status}. Try again shortly.`);
    }
    const data: unknown = await res.json();
    const url =
      typeof data === 'object' && data !== null && 'imageUrl' in data
        ? String((data as { imageUrl: unknown }).imageUrl)
        : '';
    if (!url) throw new Error('The rendering service did not return an image.');
    return {
      imageUrl: url,
      caption: 'Generated by your configured rendering service. Conceptual, not a photograph of a real building.',
      providerId: 'remote',
    };
  },
};

export function activeProvider(): VisualisationProvider {
  return remoteProvider.available ? remoteProvider : localProvider;
}

export function allProviders(): VisualisationProvider[] {
  return [localProvider, remoteProvider];
}
